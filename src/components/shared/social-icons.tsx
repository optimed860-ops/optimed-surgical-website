/** Brand glyphs for footer social links (simple single-colour marks). */

export type SocialKey = "facebook" | "instagram" | "linkedin" | "youtube";

export const SOCIAL_NETWORKS: { key: SocialKey; label: string; match: RegExp; placeholder: string }[] = [
  { key: "facebook", label: "Facebook", match: /facebook\.com|fb\.com/i, placeholder: "https://www.facebook.com/yourpage" },
  { key: "instagram", label: "Instagram", match: /instagram\.com/i, placeholder: "https://www.instagram.com/yourpage" },
  { key: "linkedin", label: "LinkedIn", match: /linkedin\.com/i, placeholder: "https://www.linkedin.com/company/yourpage" },
  { key: "youtube", label: "YouTube", match: /youtube\.com|youtu\.be/i, placeholder: "https://www.youtube.com/@yourchannel" },
];

/** Finds the saved link for a network, by its label or its web address. */
export function findSocial(links: { label: string; url: string }[], key: SocialKey) {
  const net = SOCIAL_NETWORKS.find((n) => n.key === key)!;
  return links.find((l) => l.label.toLowerCase() === net.label.toLowerCase() || net.match.test(l.url));
}

